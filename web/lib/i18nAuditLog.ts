// AA-1129 (S285 live check of the access log): every audit code the API writes (lib/auditCodes.json, read from the
// API code by api/scripts/audit_codes.py) has words here, so a line of Settings > Access log is a plain sentence:
//
// - `log.say.<action>`: a whole sentence without the actor ("created a campaign"); the object is not appended, but a
//   sentence may name it with `{obj}` ("removed {obj}" -> "removed team member Agent 2").
//   Codes that only a refusal writes (app.permissions.Action) read "tried to …" (the line also shows "Refused").
// - `log.act.<action>`: a verb the object follows ("restored from the trash" + "a client").
// - `log.obj.<kind>`: the object's noun; a noun that starts with "the" names the one object ("the agency").
// - `field.<code>` / `why.<code>`: the details shown and the reason.
//
// An unknown code (a newer API) never prints as a raw code: lib/accessLog.ts words it generically.

