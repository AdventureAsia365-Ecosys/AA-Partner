function prefixed<T extends Record<string, string>, P extends string>(prefix: P, values: T): { [K in keyof T & string as `${P}${K}`]: string } {
  return Object.fromEntries(Object.entries(values).map(([k, v]) => [`${prefix}${k}`, v])) as { [K in keyof T & string as `${P}${K}`]: string };
}

