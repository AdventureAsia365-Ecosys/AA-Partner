export type AcademyKey = keyof typeof academyEn;
export type AcademyDict = Record<AcademyKey, string>;

/** Only the academy strings, for the academy's client components (not the whole web dictionary). */
export function academyDict(lang: "en" | "vi"): AcademyDict {
  return lang === "vi" ? academyVi : academyEn;
}

/** ``say(dict, "academy.minutes", { n: 5 })``: one academy string with its {name} slots filled. */
export function say(dict: AcademyDict, key: AcademyKey, vars: Record<string, string | number> = {}): string {
  return dict[key].replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}
